/** Returns an inline SVG string for `name`. */
export function icon(name: IconName, className = "vb-icon"): string {
  return `<svg class="${className}" aria-hidden="true" focusable="false" xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${PATHS[name]}</svg>`;
}

