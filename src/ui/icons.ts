/** Replaces every `[data-icon]` placeholder inside `root` with its SVG. */
export function hydrateIcons(root: ParentNode = document): void {
  root.querySelectorAll<HTMLElement>("[data-icon]").forEach((el) => {
    const name = el.dataset.icon as IconName;
    if (!(name in PATHS)) return;
    el.insertAdjacentHTML("afterbegin", icon(name, el.dataset.iconClass || "vb-icon"));
    el.removeAttribute("data-icon");
  });
  root.querySelectorAll<HTMLElement>("[data-brand-symbol]").forEach((el) => {
    el.insertAdjacentHTML("afterbegin", brandSymbol(el.dataset.brandSymbol || "vb-brand-symbol"));
    el.removeAttribute("data-brand-symbol");
  });
}
